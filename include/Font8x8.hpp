// Retorna o glifo (8 bytes) para um code point Unicode, ou nullptr se não suportado.
inline const unsigned char* FindGlyph(unsigned int codepoint) {
    if (codepoint >= (unsigned int)FONT8x8_FIRST_CHAR && codepoint <= (unsigned int)FONT8x8_LAST_CHAR)
        return FONT8x8[codepoint - FONT8x8_FIRST_CHAR];
    for (int i = 0; i < FONT8x8_EXTRA_COUNT; i++)
        if (FONT8x8_EXTRA_CODEPOINTS[i] == codepoint) return FONT8x8_EXTRA[i];
    return nullptr;
}

